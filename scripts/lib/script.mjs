// Shared helpers for the timing scripts: parse script.json into spoken word
// tokens, turn per-token timings into the timeline module Remotion imports.
import fs from "node:fs";
import path from "node:path";

const BREAK_AFTER = /[.,!?;:…—]$/;
const BEAT_KEYS = ["pose", "chapter", "counter", "counterLabel", "counterDanger", "hideTimeline"];

export const parseArgs = (argv) => {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith("--")) {
      const [k, v] = a.slice(2).split("=");
      if (v !== undefined) out[k] = v;
      else if (argv[i + 1] !== undefined && !argv[i + 1].startsWith("--")) out[k] = argv[++i];
      else out[k] = true;
    } else out._.push(a);
  }
  return out;
};

export const loadScript = (file) => {
  const script = JSON.parse(fs.readFileSync(file, "utf8"));
  if (!Array.isArray(script.beats) || script.beats.length === 0) {
    throw new Error(`${file}: "beats" must be a non-empty array`);
  }
  return script;
};

export const normalize = (s) => s.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, "");

// A whitespace-separated word, or a {display|spoken} pair whose spoken half may
// contain spaces: "{RLS|R L S}." shows "RLS." but the voice says "R L S."
const PIECE = /\S*\{[^}|]+\|[^}]+\}\S*|\S+/g;
const PAIR = /^(.*)\{([^}|]+)\|([^}]+)\}(.*)$/;

// One token per caption word. `text` (returned) is the exact narration sent to
// TTS; each token's charStart/charEnd index into it. Token `text` is what the
// caption shows, `spoken` what the voice says. [brackets] mark emphasis and may
// span several words.
export const tokenize = (script) => {
  const tokens = [];
  let text = "";
  script.beats.forEach((beat, b) => {
    const label = beat.id ?? `#${b + 1}`;
    if (typeof beat.say !== "string" || !beat.say.trim()) throw new Error(`beat ${label}: "say" is empty`);
    let inBracket = false;
    for (const raw of beat.say.trim().match(PIECE)) {
      const opens = raw.includes("[");
      const closes = raw.includes("]");
      const emphasis = inBracket || opens;
      if (opens) inBracket = true;
      if (closes) inBracket = false;
      let word = raw.replace(/[[\]]/g, "");
      let spoken = word;
      const pair = word.match(PAIR);
      if (pair) {
        word = pair[1] + pair[2] + pair[4];
        spoken = pair[1] + pair[3] + pair[4];
      }
      if (!word) continue;
      if (text.length) text += " ";
      tokens.push({ text: word, spoken, emphasis, beat: b, charStart: text.length, charEnd: text.length + spoken.length - 1 });
      text += spoken;
    }
    if (inBracket) throw new Error(`beat ${label}: unclosed "[" in "${beat.say}"`);
  });
  tokens.forEach((t, i) => {
    const next = tokens[i + 1];
    t.pageBreakAfter = BREAK_AFTER.test(t.text) || !next || next.beat !== t.beat;
  });
  return { text, tokens };
};

// timings[i] = { startMs, endMs } for tokens[i]
export const buildTimeline = (script, tokens, timings) => {
  const words = tokens.map((t, i) => {
    const w = { text: t.text, startMs: Math.round(timings[i].startMs), endMs: Math.round(timings[i].endMs) };
    if (t.emphasis) w.emphasis = true;
    if (t.pageBreakAfter) w.pageBreakAfter = true;
    w.beat = t.beat;
    return w;
  });
  const beats = script.beats.map((b, i) => {
    let first = -1;
    let last = -1;
    words.forEach((w, k) => {
      if (w.beat === i) {
        if (first < 0) first = k;
        last = k;
      }
    });
    const beat = {
      id: b.id ?? `beat-${i + 1}`,
      text: tokens
        .filter((t) => t.beat === i)
        .map((t) => t.text)
        .join(" "),
      scene: b.scene ?? "Missing",
      mode: b.mode === "light" ? "light" : "dark",
    };
    for (const k of BEAT_KEYS) if (b[k] !== undefined) beat[k] = b[k];
    Object.assign(beat, { startMs: words[first].startMs, endMs: words[last].endMs, firstWord: first, lastWord: last });
    return beat;
  });
  return { words, beats };
};

export const writeTimeline = (outFile, script, timeline, voiceover, generator) => {
  const meta = {
    title: script.title ?? "",
    format: script.format === "B" ? "B" : "A",
    chapters: script.chapters ?? [],
    counterLabel: script.counterLabel ?? "",
    voiceover: voiceover ?? null,
  };
  const list = (arr) => `[\n${arr.map((x) => `  ${JSON.stringify(x)}`).join(",\n")}\n]`;
  const src = `// Generated by scripts/${generator} from script.json. Re-run the script instead of editing.
import type { Beat, Word } from "../lib/timing";

export const meta: { title: string; format: "A" | "B"; chapters: string[]; counterLabel: string; voiceover: string | null } = ${JSON.stringify(meta, null, 2)};

export const beats: Beat[] = ${list(timeline.beats)};

export const words: Word[] = ${list(timeline.words)};
`;
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, src);
  const end = timeline.words[timeline.words.length - 1].endMs;
  console.log(`Wrote ${outFile}: ${timeline.beats.length} beats, ${timeline.words.length} words, ${(end / 1000).toFixed(1)}s of narration.`);
};

// Reads KEY=VALUE pairs from ./.env without adding a dependency.
export const readDotEnv = (file = ".env") => {
  if (!fs.existsSync(file)) return {};
  const env = {};
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
  return env;
};

// ElevenLabs alignment -> per-token timings. `characters` normally equals the
// sent text char-for-char; otherwise non-space characters are matched in order.
export const timingsFromAlignment = (text, tokens, alignment) => {
  const chars = alignment.characters;
  const map = new Array(text.length).fill(-1);
  if (chars.join("") === text) {
    for (let i = 0; i < text.length; i++) map[i] = i;
  } else {
    let j = 0;
    for (let i = 0; i < text.length; i++) {
      if (/\s/.test(text[i])) continue;
      while (j < chars.length && chars[j].toLowerCase() !== text[i].toLowerCase()) j++;
      map[i] = Math.min(j, chars.length - 1);
      j++;
    }
  }
  return tokens.map((t) => ({
    startMs: alignment.character_start_times_seconds[map[t.charStart]] * 1000,
    endMs: alignment.character_end_times_seconds[map[t.charEnd]] * 1000,
  }));
};

// Transcribed words ({ text, startMs, endMs }) -> per-token timings (null when
// unmatched). Each script word looks ahead a few heard words and may join up
// to 3 heard pieces ("vibe" + "coded").
export const alignToHeard = (tokens, heardWords) => {
  const heard = heardWords.map((h) => ({ ...h, norm: normalize(h.text) })).filter((h) => h.norm);
  const timings = new Array(tokens.length).fill(null);
  let j = 0;
  for (let i = 0; i < tokens.length; i++) {
    const target = normalize(tokens[i].spoken);
    for (let k = j; k < Math.min(heard.length, j + 8) && !timings[i]; k++) {
      let acc = "";
      for (let n = 0; n < 3 && k + n < heard.length; n++) {
        acc += heard[k + n].norm;
        if (acc === target) {
          timings[i] = { startMs: heard[k].startMs, endMs: heard[k + n].endMs };
          j = k + n + 1;
          break;
        }
        if (!target.startsWith(acc)) break;
      }
    }
  }
  return timings;
};

// Spread missing timings evenly between known neighbours.
export const fillGaps = (timings, fallbackWordMs = 330) => {
  let i = 0;
  while (i < timings.length) {
    if (timings[i]) {
      i++;
      continue;
    }
    let j = i;
    while (j < timings.length && !timings[j]) j++;
    const from = i > 0 ? timings[i - 1].endMs : 0;
    const to = j < timings.length ? timings[j].startMs : from + (j - i) * fallbackWordMs;
    const step = (to - from) / (j - i);
    for (let k = i; k < j; k++) timings[k] = { startMs: from + step * (k - i), endMs: from + step * (k - i + 0.9) };
    i = j;
  }
  return timings;
};
